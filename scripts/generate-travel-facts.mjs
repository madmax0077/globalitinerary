// Generates src/data/travel-facts.generated.ts:
//   - Power plugs / voltage / frequency  (IEC via benjiao/world-plugs)
//   - General emergency number           (sandunwira/CrisisHotlines, Wikipedia-sourced)
//   - Coarse cost tier                    (World Bank income classification)
//   - Tap-water guidance                  (curated conservative safe-list)
// Keyed by ISO 3166-1 alpha-2 (UPPERCASE). Run: node scripts/generate-travel-facts.mjs
import { writeFileSync } from "node:fs";

// Local, one-off data-gen script: relax TLS so it works behind corporate proxies.
process.env.NODE_TLS_REJECT_UNAUTHORIZED = "0";

const PLUGS_URL =
  "https://raw.githubusercontent.com/benjiao/world-plugs/master/world-plugs.csv";
const EMERGENCY_URL =
  "https://raw.githubusercontent.com/sandunwira/CrisisHotlines/master/information.min.json";
const WB_URL = "https://api.worldbank.org/v2/country?format=json&per_page=400";

// Countries where tap water is very widely considered safe to drink for visitors.
// Conservative on purpose — everything else is shown as "use bottled/filtered".
const TAP_SAFE = new Set(
  ("AD AT AU BE CA CH CZ DE DK EE ES FI FR GB GR HR HU IE IS IL IT JP KR LI LT LU LV " +
    "MC MT NL NO NZ PL PT SE SG SI SK SM US")
    .split(" ")
);

const COST_TIER = {
  "High income": "high",
  "Upper middle income": "mid",
  "Lower middle income": "budget",
  "Low income": "budget",
};

function parseCsvLine(line) {
  // Handles quoted fields that contain commas (e.g. Japan's "50 Hz, 60 Hz").
  const out = [];
  let cur = "";
  let inQ = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      inQ = !inQ;
    } else if (ch === "," && !inQ) {
      out.push(cur);
      cur = "";
    } else {
      cur += ch;
    }
  }
  out.push(cur);
  return out.map((s) => s.trim());
}

async function main() {
  console.log("Fetching plugs…");
  const plugsCsv = await (await fetch(PLUGS_URL)).text();
  console.log("Fetching emergency numbers…");
  const emergency = await (await fetch(EMERGENCY_URL)).json();
  console.log("Fetching World Bank income levels…");
  const wb = await (await fetch(WB_URL)).json();

  const facts = {};
  const touch = (iso2) => (facts[iso2] ??= {});

  // Plugs
  const rows = plugsCsv.split("\n").slice(1).filter((l) => l.includes(","));
  for (const line of rows) {
    const [, code, frequency, , plugType, voltage] = parseCsvLine(line);
    if (!code) continue;
    const iso2 = code.trim().toUpperCase();
    const f = touch(iso2);
    f.plugs ??= { types: [], voltage: "", frequency: "" };
    const letter = (plugType || "").replace(/type\s*/i, "").trim();
    if (letter && !f.plugs.types.includes(letter)) f.plugs.types.push(letter);
    if (!f.plugs.voltage && voltage) f.plugs.voltage = voltage.replace(/\s+/g, "");
    if (!f.plugs.frequency && frequency) f.plugs.frequency = frequency.replace(/\s+/g, "");
  }

  // Emergency (general) number
  for (const c of emergency) {
    const iso2 = (c["alpha-2"] || "").toUpperCase();
    if (!iso2 || !Array.isArray(c.hotlines)) continue;
    const em = c.hotlines.find((h) => /emergency/i.test(h.name)) || c.hotlines[0];
    const nums = (em?.numbers || []).filter((n) => /^[0-9 ]{2,6}$/.test(n));
    if (nums.length) touch(iso2).emergency = nums.slice(0, 3);
  }

  // Cost tier from World Bank income group
  for (const c of wb[1] || []) {
    if (!c || c.region?.value === "Aggregates") continue;
    const iso2 = (c.iso2Code || "").toUpperCase();
    const tier = COST_TIER[c.incomeLevel?.value];
    if (iso2 && tier) touch(iso2).cost = tier;
  }

  // Tap water
  for (const iso2 of TAP_SAFE) touch(iso2).tapWater = "safe";
  // Everything else defaults to caution at render time.

  const out = `// AUTO-GENERATED by scripts/generate-travel-facts.mjs — do not edit by hand.
// Sources: benjiao/world-plugs (IEC), sandunwira/CrisisHotlines (Wikipedia),
// World Bank income classification, and a conservative curated tap-water safe-list.
// Keyed by ISO 3166-1 alpha-2 (UPPERCASE).

export type TravelFacts = {
  plugs?: { types: string[]; voltage: string; frequency: string };
  emergency?: string[];
  cost?: "budget" | "mid" | "high";
  tapWater?: "safe";
};

export const travelFacts: Record<string, TravelFacts> = ${JSON.stringify(facts)};
`;

  writeFileSync("src/data/travel-facts.generated.ts", out, "utf8");
  console.log(`Wrote src/data/travel-facts.generated.ts: ${Object.keys(facts).length} countries.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
