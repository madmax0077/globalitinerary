// Generates src/data/country-info.generated.ts (real Wikivoyage prose keyed by slug).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function slugify(input) {
  return input
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)+/g, "");
}

const raw = fs.readFileSync(path.join(__dirname, "country-info.json"), "utf8").replace(/^\uFEFF/, "");
const byName = JSON.parse(raw);

const bySlug = {};
for (const [name, info] of Object.entries(byName)) {
  if (!info || Object.keys(info).length === 0) continue;
  bySlug[slugify(name)] = info;
}

const header = `// AUTO-GENERATED by scripts/generate-country-info.mjs — do not edit by hand.
// Real destination prose sourced from Wikivoyage (CC BY-SA 4.0).
export interface CountryInfo {
  understand?: string;
  getIn?: string;
  getAround?: string;
  talk?: string;
  buy?: string;
  eat?: string;
  staySafe?: string;
  stayHealthy?: string;
  connect?: string;
  respect?: string;
  festivals?: string;
}

export const countryInfo: Record<string, CountryInfo> = ${JSON.stringify(bySlug, null, 2)};

export function getCountryInfo(slug: string): CountryInfo | undefined {
  return countryInfo[slug];
}
`;

fs.writeFileSync(path.join(root, "src", "data", "country-info.generated.ts"), header);
console.log(`Generated info for ${Object.keys(bySlug).length} countries -> src/data/country-info.generated.ts`);
