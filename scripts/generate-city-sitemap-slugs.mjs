/**
 * Writes src/data/city-sitemap-slugs.generated.ts — slugs only, no city objects.
 * Run: node scripts/generate-city-sitemap-slugs.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const targets = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts", "city-targets.json"), "utf8"));
const redirectSrc = fs.readFileSync(path.join(ROOT, "src", "data", "city-slug-redirects.ts"), "utf8");
const redirectKeys = new Set(
  [...redirectSrc.matchAll(/^\s*"([^"]+)":/gm)].map((m) => m[1]),
);

const slugs = [...new Set(targets.map((t) => t.slug).filter((s) => s && !redirectKeys.has(s)))].sort();
const out = `// AUTO-GENERATED by scripts/generate-city-sitemap-slugs.mjs — do not edit.
export const citySitemapSlugs: readonly string[] = ${JSON.stringify(slugs, null, 2)};
`;
const dest = path.join(ROOT, "src", "data", "city-sitemap-slugs.generated.ts");
fs.writeFileSync(dest, out);
console.log(`Wrote ${slugs.length} city sitemap slugs -> ${path.relative(ROOT, dest)}`);
