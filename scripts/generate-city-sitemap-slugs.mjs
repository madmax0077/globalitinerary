/**
 * Writes src/data/city-sitemap-slugs.generated.ts — indexable slugs only, no
 * city objects. This must use the same quality gate as city page metadata so a
 * URL listed in the sitemap never responds with `noindex`.
 *
 * Run: node scripts/generate-city-sitemap-slugs.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

/*
 * The merged city objects and isCityIndexable live in TypeScript. Register a
 * small CommonJS transpile hook so this plain Node script can load the exact
 * production data without adding tsx/ts-node as a dependency.
 */
const require = createRequire(import.meta.url);
const ts = require("typescript");
const Module = require("node:module");
const originalResolveFilename = Module._resolveFilename;

Module._resolveFilename = function resolveAlias(request, parent, isMain, options) {
  let resolvedRequest = request.startsWith("@/")
    ? path.join(ROOT, "src", request.slice(2))
    : request;
  // Node checks .json before our custom .ts extension. Prefer the TypeScript
  // module explicitly when both share a basename (cities.generated.ts/json).
  if (path.isAbsolute(resolvedRequest) && fs.existsSync(`${resolvedRequest}.ts`)) {
    resolvedRequest = `${resolvedRequest}.ts`;
  }
  return originalResolveFilename.call(this, resolvedRequest, parent, isMain, options);
};

require.extensions[".ts"] = (module, filename) => {
  const source = fs.readFileSync(filename, "utf8");
  const output = ts.transpileModule(source, {
    fileName: filename,
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      esModuleInterop: true,
      resolveJsonModule: true,
    },
  });
  module._compile(output.outputText, filename);
};

const { cities } = require(path.join(ROOT, "src", "data", "cities.ts"));
const { isCityIndexable } = require(
  path.join(ROOT, "src", "lib", "content-legitimacy.ts"),
);

const slugs = cities
  .filter(isCityIndexable)
  .map((city) => city.slug)
  .sort();

const out = `// AUTO-GENERATED by scripts/generate-city-sitemap-slugs.mjs — do not edit.
// Contains only cities that pass the same quality gate used by page metadata.
export const citySitemapSlugs: readonly string[] = ${JSON.stringify(slugs, null, 2)};
`;
const dest = path.join(ROOT, "src", "data", "city-sitemap-slugs.generated.ts");
fs.writeFileSync(dest, out);
console.log(
  `Wrote ${slugs.length}/${cities.length} indexable city slugs -> ${path.relative(ROOT, dest)}`,
);
