const cityTz = {};
const byCountry = new Map();
for (const t of targets) {
  if (t.timezone && String(t.timezone).includes("/")) {
    cityTz[t.slug] = t.timezone;
    const arr = byCountry.get(t.countrySlug) || [];
    arr.push(t);
    byCountry.set(t.countrySlug, arr);
  }
}

const countryTz = {};
for (const [slug, list] of byCountry) {
  const capital = list.find((x) => x.isCapital && x.timezone?.includes("/"));
  if (capital) {
    countryTz[slug] = capital.timezone;
    continue;
  }
  // mode
  const counts = new Map();
  for (const t of list) {
    if (!t.timezone?.includes("/")) continue;
    counts.set(t.timezone, (counts.get(t.timezone) || 0) + 1);
  }
  let best = null;
  let bestN = 0;
  for (const [tz, n] of counts) {
    if (n > bestN) {
      best = tz;
      bestN = n;
    }
  }
  countryTz[slug] = best || COUNTRY_FALLBACK[slug] || null;
}
for (const [slug, tz] of Object.entries(COUNTRY_FALLBACK)) {
  if (!countryTz[slug]) countryTz[slug] = tz;
}

// Write TS modules
const cityOut = `/** AUTO-GENERATED by scripts/build-timezones.mjs — IANA zones per city slug */
export const cityTimezones: Record<string, string> = ${JSON.stringify(cityTz, null, 2)};
`;
const countryOut = `/** AUTO-GENERATED by scripts/build-timezones.mjs — primary IANA zone per country slug */
export const countryTimezones: Record<string, string> = ${JSON.stringify(countryTz, null, 2)};
`;
fs.writeFileSync(path.join(root, "src", "data", "city-timezones.generated.ts"), cityOut);
fs.writeFileSync(path.join(root, "src", "data", "country-timezones.generated.ts"), countryOut);
fs.writeFileSync(
  path.join(__dirname, "country-timezones.json"),
  JSON.stringify(countryTz, null, 2),
);

// Patch countries.generated.ts timezone fields
function extractRaw(src) {
  const marker = "const raw: Gen[] = ";
  const start = src.indexOf(marker);
  const jsonStart = start + marker.length;
  const end = src.indexOf("\n];\n\nexport", jsonStart);
  return { before: src.slice(0, jsonStart), json: src.slice(jsonStart, end + 2), after: src.slice(end + 2) };
}

const countryFile = path.join(root, "src", "data", "countries.generated.ts");
const src = fs.readFileSync(countryFile, "utf8");
const { before, json, after } = extractRaw(src);
const data = JSON.parse(json);
let patched = 0;
for (const c of data) {
  const tz = countryTz[c.slug];
  if (tz && c.timezone !== tz) {
    c.timezone = tz;
    patched++;
  }
}
fs.writeFileSync(countryFile, before + JSON.stringify(data, null, 2) + after);

